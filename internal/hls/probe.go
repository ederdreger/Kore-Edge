package hls

import (
	"bytes"
	"context"
	"encoding/json"
	"io"
	"os/exec"
	"time"
)

type cappedBuffer struct {
	bytes.Buffer
	limit int
}

func (b *cappedBuffer) Write(p []byte) (int, error) {
	if b.Len()+len(p) > b.limit {
		return 0, ErrUnavailable
	}
	return b.Buffer.Write(p)
}
func commandOutput(ctx context.Context, path string, args []string, input io.Reader, limit int) ([]byte, error) {
	cmd := exec.CommandContext(ctx, path, args...)
	cmd.Stdin = input
	cmd.WaitDelay = time.Second
	out := &cappedBuffer{limit: limit}
	cmd.Stdout = out
	if cmd.Run() != nil {
		return nil, ErrUnavailable
	}
	return out.Bytes(), nil
}
func ValidateCodecs(data []byte) error {
	var info struct {
		Streams []struct {
			Type  string `json:"codec_type"`
			Codec string `json:"codec_name"`
		} `json:"streams"`
	}
	if json.Unmarshal(data, &info) != nil || len(info.Streams) != 2 {
		return ErrUnavailable
	}
	video, audio := false, false
	for _, s := range info.Streams {
		switch {
		case s.Type == "video" && s.Codec == "h264" && !video:
			video = true
		case s.Type == "audio" && s.Codec == "aac" && !audio:
			audio = true
		default:
			return ErrUnavailable
		}
	}
	if !video || !audio {
		return ErrUnavailable
	}
	return nil
}

// Verify probes bytes actually generated by the configured executable. The live
// source uses the same fixed codec arguments; no arbitrary URL/file is accepted.
func Verify(ctx context.Context, c Config) error {
	ctx, cancel := context.WithTimeout(ctx, 10*time.Second)
	defer cancel()
	sample, e := commandOutput(ctx, c.FFmpeg, SyntheticArgs(false), nil, 4*1024*1024)
	if e != nil {
		return e
	}
	info, e := commandOutput(ctx, c.FFprobe, []string{"-v", "error", "-protocol_whitelist", "pipe", "-f", "mpegts", "-show_entries", "stream=codec_type,codec_name", "-of", "json", "pipe:0"}, bytes.NewReader(sample), 64*1024)
	if e != nil {
		return e
	}
	return ValidateCodecs(info)
}
